const { writeFileSync, mkdirSync } = require('fs')
const { join } = require('path')

const pkg = require('../package.json')

const now = new Date()
const pad = (n) => String(n).padStart(2, '0')
const buildTime = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())}:${pad(now.getSeconds())}`

const content = `// Auto-generated by scripts/generate-build-info.js — do not edit manually
export const BUILD_INFO = {
  version: "${pkg.version}",
  buildTime: "${buildTime}",
  environment: process.env.NODE_ENV ?? "development"
}
`

const outDir = join(__dirname, '..', 'src', 'shared')
mkdirSync(outDir, { recursive: true })
writeFileSync(join(outDir, 'build-info.ts'), content, 'utf-8')
console.log(`[build-info] version=${pkg.version} buildTime=${buildTime}`)
